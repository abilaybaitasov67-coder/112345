import { isSupabaseConfigured, supabase } from './supabase';

const system = `Ты безопасный персональный фитнес-тренер для подростков.
Отвечай на русском, дружелюбно и не длиннее 6 предложений.
Не ставь диагнозы, не советуй экстремальные диеты, добавки или опасные веса.
При боли, травме или плохом самочувствии советуй прекратить упражнение и обратиться ко взрослому или врачу.`;

export async function askFitnessCoach(question: string) {
  if (isSupabaseConfigured) {
    const { data, error } = await supabase.functions.invoke<{ text?: string }>('ai', {
      body: { prompt: question, system },
    });
    if (!error && data?.text) return data.text;
  }
  return offlineCoachAnswer(question);
}

function offlineCoachAnswer(question: string) {
  const text = question.toLowerCase();
  if (text.includes('присед')) {
    return 'Поставь стопы примерно на ширине плеч и направь носки немного наружу. Отводи таз назад, держи спину ровно, а колени направляй вслед за носками. Начни без веса и остановись, если появляется боль.';
  }
  if (text.includes('устал') || text.includes('отдых')) {
    return 'Снизь темп и отдохни 60–90 секунд. Если кружится голова, болит или стало плохо — закончи тренировку и скажи взрослому. Пропущенная тренировка безопаснее занятия через плохое самочувствие.';
  }
  if (text.includes('разм')) {
    return 'Сделай 5 минут лёгких движений: шаг на месте, круги плечами, наклоны таза и неглубокие приседания. Разминка должна согреть, а не утомить. Резкие движения и растяжку через боль делать не нужно.';
  }
  return 'Начинай с лёгкого варианта и следи за спокойной техникой. Оставляй запас в 2–3 повтора и увеличивай нагрузку постепенно. Если вопрос связан с болью или травмой, остановись и обратись ко взрослому или врачу.';
}
